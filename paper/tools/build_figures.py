@figure("fig_coverage_matrix")
def _():
    v = D.view()
    fig, axes = plt.subplots(
        len(D.BENCHMARKS), len(D.TOPO_ORDER), figsize=(9.0, 8.4), sharex=True, sharey=True
    )
    vmax = 0
    grids = {}
    for bi, b in enumerate(D.BENCHMARKS):
        for ti, t in enumerate(D.TOPO_ORDER):
            sub = v[(v.benchmark == b) & (v.topology == t)]
            g = np.zeros((len(D.SIZE_ORDER), len(D.REAS_ORDER)))
            for si, s in enumerate(D.SIZE_ORDER):
                for ri, r in enumerate(D.REAS_ORDER):
                    g[si, ri] = len(sub[(sub.model_size == s) & (sub.reasoning_level == r)])
            grids[(b, t)] = g
            vmax = max(vmax, g.max())
    for bi, b in enumerate(D.BENCHMARKS):
        for ti, t in enumerate(D.TOPO_ORDER):
            ax = axes[bi, ti]
            g = grids[(b, t)]
            ax.imshow(g, cmap="Blues", vmin=0, vmax=vmax, aspect="auto")
            for si in range(g.shape[0]):
                for ri in range(g.shape[1]):
                    n = int(g[si, ri])
                    ax.text(
                        ri, si, str(n), ha="center", va="center", fontsize=6,
                        color="white" if n > 0.6 * vmax else "#334155",
                    )
            if bi == 0:
                ax.set_title(D.TOPO_LABEL[t])
            if ti == 0:
                ax.set_ylabel(f"{D.BENCH_LABEL[b]}\nmodel size")
                ax.set_yticks(range(len(D.SIZE_ORDER)), D.SIZE_ORDER)
            if bi == len(D.BENCHMARKS) - 1:
                ax.set_xticks(range(len(D.REAS_ORDER)), D.REAS_ORDER, rotation=45, ha="right")
            ax.grid(False)
    fig.suptitle("Seed-level cells per design point (post-trim core view)", y=0.995)
    fig.tight_layout()
    savepdf(fig, "fig_coverage_matrix")


@figure("fig_stratum_caterpillar")
def _():
    s = D.csv("axis_relationships/axis_stratified_contrasts.csv")
    s = s[s.metric == "accuracy"].copy()
    pooled = D.csv("axis_relationships/axis_matched_contrasts.csv")
    pooled = pooled[pooled.metric == "accuracy"]
    fig, axes = plt.subplots(2, 3, figsize=(9.2, 5.4))
    contrasts = sorted(s.contrast.unique())
    for ax, cname in zip(axes.ravel(), contrasts):
        sub = s[s.contrast == cname].sort_values("delta").reset_index(drop=True)
        x = np.arange(len(sub))
        ax.vlines(x, sub.ci_low, sub.ci_high, color="#cbd5e1", lw=0.7)
        colors = [
            P.BENCH_COLORS.get(b, P.PRIMARY) for b in sub.benchmark
        ]
        ax.scatter(x, sub.delta, s=5, c=colors, zorder=3)
        ax.axhline(0, color="0.4", lw=0.8, ls="--")
        pv = pooled[pooled.contrast == cname].delta.mean()
        if np.isfinite(pv):
            ax.axhline(pv, color="#dc2626", lw=1.0)
        ax.set_title(cname.replace("_", " "), fontsize=8)
        ax.set_xlabel("stratum (sorted)")
        ax.set_ylabel(r"$\Delta$ accuracy")
        frac = ((sub.ci_low > 0) | (sub.ci_high < 0)).mean()
        ax.text(
            0.02, 0.95, f"$k$={len(sub)}, {100 * frac:.0f}% excl. 0",
            transform=ax.transAxes, va="top", fontsize=6.5, color="#334155",
        )
    for ax in axes.ravel()[len(contrasts):]:
        ax.axis("off")
    handles = [
        plt.Line2D([], [], marker="o", ls="", color=P.BENCH_COLORS[b], label=D.BENCH_LABEL[b], ms=4)
        for b in D.BENCHMARKS
    ]
    handles.append(plt.Line2D([], [], color="#dc2626", label="pooled matched contrast"))
    fig.legend(handles=handles, loc="lower center", ncol=5, frameon=False, bbox_to_anchor=(0.5, -0.03))
    fig.suptitle("Every stratified accuracy contrast, sorted within contrast", y=1.0)
    fig.tight_layout()
    savepdf(fig, "fig_stratum_caterpillar")


