@figure("fig_delta_by_bench_topo")
def _():
    v = D.view()
    mcq = v[v.benchmark.isin(D.MCQ)]
    fig, axes = plt.subplots(1, 2, figsize=(8.4, 3.4), sharey=False)
    for ax, (col, title) in zip(
        axes,
        [("delta_vote_prim", r"$\Delta$ECE, vote fraction"),
         ("delta_fp_prim", r"$\Delta$ECE, final producer")],
    ):
        width = 0.2
        for ti, t in enumerate([x for x in D.TOPO_ORDER if x != "single_agent"]):
            xs, ys, es = [], [], []
            for bi, b in enumerate(D.MCQ):
                sub = mcq[(mcq.benchmark == b) & (mcq.topology == t)][col].dropna()
                if not len(sub):
                    continue
                xs.append(bi + (ti - 1) * width)
                ys.append(sub.mean())
                es.append(sub.std() / np.sqrt(len(sub)))
            ax.bar(xs, ys, width=width * 0.92, yerr=es, capsize=2,
                   color=P.TOPO_COLORS[t], label=D.TOPO_LABEL[t])
        ax.axhline(0, color="0.4", lw=0.8)
        ax.set_xticks(range(len(D.MCQ)), [D.BENCH_LABEL[b] for b in D.MCQ])
        ax.set_title(title)
        ax.set_ylabel(r"$\Delta$ECE")
    axes[0].legend(frameon=False, fontsize=7)
    fig.suptitle("Coordination calibration penalty by benchmark and topology", y=1.02)
    fig.tight_layout()
    savepdf(fig, "fig_delta_by_bench_topo")


