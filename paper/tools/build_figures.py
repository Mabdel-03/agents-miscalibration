#!/usr/bin/env python
"""Generate the vector figure panels that do not already exist in analysis/figures/.

Output is PDF rather than PNG: at this point count vector output is both smaller and
sharper than a 180 dpi raster.  ``nb_lib.plots.savefig`` is hard-coded to PNG, so the
style and colour constants are reused but the writer is replaced.

Usage:  build_figures.py --out figures/panels
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
import paperdata as D  # noqa: E402

sys.path.insert(0, str(D.REPO))
from analysis.nb_lib import plots as P  # noqa: E402

OUT = Path("figures/panels")
BUILDERS: dict[str, callable] = {}


def figure(name: str):
    def deco(fn):
        BUILDERS[name] = fn
        return fn

    return deco


def savepdf(fig, name: str) -> Path:
    out = OUT / f"{name}.pdf"
    out.parent.mkdir(parents=True, exist_ok=True)
    # Suppressing the creation date keeps regenerated bytes identical run to run.
    fig.savefig(out, bbox_inches="tight", metadata={"CreationDate": None})
    plt.close(fig)
    return out


def style():
    P.style()
    plt.rcParams.update(
        {
            "pdf.fonttype": 42,
            "font.family": "serif",
            "font.serif": ["Nimbus Roman", "Times New Roman", "DejaVu Serif"],
            "font.size": 8.5,
            "axes.titlesize": 9,
            "axes.labelsize": 8.5,
            "legend.fontsize": 7.5,
            "xtick.labelsize": 7.5,
            "ytick.labelsize": 7.5,
        }
    )


