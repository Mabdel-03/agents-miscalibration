def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="figures/panels")
    ap.add_argument("--only", default="*")
    args = ap.parse_args()

    global OUT
    OUT = Path(args.out)
    OUT.mkdir(parents=True, exist_ok=True)
    style()

    from fnmatch import fnmatch

    names = [n for n in BUILDERS if fnmatch(n, args.only)]
    for n in sorted(names):
        BUILDERS[n]()
    total = sum(p.stat().st_size for p in OUT.glob("*.pdf"))
    print(f"wrote {len(names)} figure panels to {OUT} ({total / 1e6:.2f} MB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
