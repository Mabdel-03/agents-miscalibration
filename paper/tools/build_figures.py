@figure("fig_size_reasoning_heatmap")
def _():
    v = D.view()
    fig, axes = plt.subplots(1, 4, figsize=(9.6, 2.9))
    for ax, b in zip(axes, D.BENCHMARKS):
        sub = v[v.benchmark == b]
        g = np.full((len(D.SIZE_ORDER), len(D.REAS_ORDER)), np.nan)
        capped = np.zeros_like(g, dtype=bool)
        for si, s in enumerate(D.SIZE_ORDER):
            for ri, r in enumerate(D.REAS_ORDER):
                cell = sub[(sub.model_size == s) & (sub.reasoning_level == r)]
                if len(cell):
                    g[si, ri] = cell.accuracy.mean()
                    capped[si, ri] = bool(cell.ctx32b_capped.any())
        im = ax.imshow(g, cmap="viridis", aspect="auto", vmin=0.2, vmax=0.9)
        for si in range(g.shape[0]):
            for ri in range(g.shape[1]):
                if np.isnan(g[si, ri]):
                    continue
                ax.text(
                    ri, si, f"{g[si, ri]:.2f}", ha="center", va="center", fontsize=6,
                    color="white" if g[si, ri] < 0.62 else "black",
                )
                if capped[si, ri]:
                    ax.add_patch(
                        plt.Rectangle(
                            (ri - 0.5, si - 0.5), 1, 1, fill=False, hatch="///",
                            edgecolor="#dc2626", lw=0.8,
                        )
                    )
        ax.set_xticks(range(len(D.REAS_ORDER)), D.REAS_ORDER, rotation=45, ha="right")
        ax.set_yticks(range(len(D.SIZE_ORDER)), D.SIZE_ORDER)
        ax.set_title(D.BENCH_LABEL[b])
        ax.grid(False)
    fig.colorbar(im, ax=axes, shrink=0.85, label="accuracy", pad=0.015)
    fig.suptitle(
        "Capacity $\\times$ reasoning accuracy; red hatching marks context-capped 32B cells",
        y=1.04,
    )
    savepdf(fig, "fig_size_reasoning_heatmap")


